const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..', '..');
const source = fs.readFileSync(path.join(root, 'ats_backend/src/business-units/delivery-dashboard.contract.ts'), 'utf8');
const target = path.join(root, 'ats_frontend_main/lib/delivery-dashboard-contract.ts');
const generated = '// Generated by scripts/sync-delivery-contract.cjs. Do not edit directly.\n' + source;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== generated) throw new Error('Delivery dashboard contract is out of sync');
} else fs.writeFileSync(target, generated);
