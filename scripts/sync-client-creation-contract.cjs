const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.resolve(__dirname, '../../ats_backend/src/clients/client-creation.contract.ts'), 'utf8');
const target = path.resolve(__dirname, '../lib/client-creation-contract.ts');
const content = '// Generated by scripts/sync-client-creation-contract.cjs. Do not edit directly.\n' + source;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== content) throw new Error('Client creation contract is out of sync.');
} else fs.writeFileSync(target, content);
