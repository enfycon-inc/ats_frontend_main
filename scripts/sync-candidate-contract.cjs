const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..', '..');
const source = fs.readFileSync(path.join(root, 'ats_backend/src/candidates/interfaces/candidate.interface.ts'), 'utf8');
const target = path.join(root, 'ats_frontend_main/lib/candidate-contract.ts');
const generated = '// Generated by scripts/sync-candidate-contract.cjs. Do not edit directly.\n' + source;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== generated) throw new Error('Candidate contract is out of sync');
} else fs.writeFileSync(target, generated);
