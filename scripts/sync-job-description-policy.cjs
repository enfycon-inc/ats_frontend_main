const fs = require('node:fs');
const path = require('node:path');
const source = path.resolve(__dirname, '../../ats_backend/src/jobs/job-description-policy.ts');
const target = path.resolve(__dirname, '../lib/job-description-policy.ts');
const generated = '// Generated by scripts/sync-job-description-policy.cjs. Do not edit directly.\n' + fs.readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== generated) throw new Error('Job description policy is out of sync. Run node scripts/sync-job-description-policy.cjs.');
} else fs.writeFileSync(target, generated);
