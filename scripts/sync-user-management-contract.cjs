const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const source = fs.readFileSync(path.join(root, 'ats_backend/src/user-management/user-management.contract.ts'), 'utf8').replace(/\r\n/g, '\n');
const target = path.join(root, 'ats_frontend_main/lib/user-management.contract.ts');
const generated = '// Generated by scripts/sync-user-management-contract.cjs. Do not edit directly.\n' + source;
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== generated) throw new Error('User management API contract is out of sync.');
} else fs.writeFileSync(target, generated);
