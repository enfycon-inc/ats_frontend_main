const request = { id: '11111111-1111-4111-8111-111111111111', requestVersion: '44444444-4444-4444-8444-444444444444', roleId: '22222222-2222-4222-8222-222222222222', fullName: 'Requester', email: 'requester@example.com', requestedRole: 'Recruiter', branchName: 'Bengaluru', businessUnitName: 'IT Staffing' };
function mount(action, error) {
  const state = [];
  let cursor = 0;
  const decisions = [];
  const jsx = (type, props) => ({ type, props });
  const component = load('app/auth/role-request/review.tsx', {
    react: { useState: initial => { const i = cursor++; if (!(i in state)) state[i] = initial; return [state[i], value => { state[i] = value; }]; } },
    'react/jsx-runtime': { jsx, jsxs: jsx },
    swr: { default: () => ({ data: request, error, isLoading: false }) },
    'next/link': { default: 'a' }, '@/components/ui/button': { Button: 'button' },
    '@/lib/ats-api': { atsApi: { auth: { decideRoleRequest: async (...args) => { decisions.push(args); return { success: true }; } } } },
  }).default;
  const render = () => { cursor = 0; return component({ requestId: request.id, version: request.requestVersion, reviewRoleId: request.roleId, initialAction: action }); };
  return { render, decisions };
}
function nodes(node) {
  if (Array.isArray(node)) return node.flatMap(nodes);
  if (!node || typeof node !== 'object') return [];
  return [node, ...nodes(node.props?.children)];
}
function text(node) {
  if (Array.isArray(node)) return node.map(text).join('');
  if (node && typeof node === 'object') return text(node.props?.children);
  return typeof node === 'string' ? node : '';
}
for (const action of ['approve', 'reject']) test(`email ${action} action requires explicit confirmation before mutation`, async () => {
  const app = mount(action);
  const output = app.render();
  assert.equal(app.decisions.length, 0);
  const confirm = nodes(output).find(node => node.type === 'button' && text(node).startsWith('Confirm'));
  assert.ok(confirm);
  await confirm.props.onClick();
  assert.equal(app.decisions.length, 1);
  assert.deepEqual(app.decisions[0], [request, action, request.roleId]);
  assert.match(text(app.render()), /Request (approved|rejected)/);
});
test('stale or unauthorized requests cannot be confirmed', () => {
  const app = mount('approve', new Error('This request has already been handled or replaced.'));
  const output = app.render();
  assert.equal(nodes(output).filter(node => node.type === 'button').length, 0);
  assert.match(text(output), /already been handled or replaced/);
  assert.equal(app.decisions.length, 0);
});
