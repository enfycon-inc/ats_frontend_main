const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');

const context = { branchId: 'branch', branchName: 'Kolkata', businessUnitId: 'unit', businessUnitName: 'India Staffing', ownerId: 'owner', ownerName: 'Account manager', market: 'INDIA', currency: 'INR', canDirectAdd: false };
function load(file, selectedContext = context, failure) {
  const exports = {};
  const localRequire = name => {
    if (name === 'swr') return { default: key => ({ data: key?.[0] === 'client-creation-context' ? selectedContext : undefined, error: failure, mutate: async () => selectedContext }) };
    if (name === '@/hooks/use-location-data') return load('hooks/use-location-data.ts');
    if (name === '@/components/page-loading-skeleton') return { PageLoadingSkeleton: () => React.createElement('div', { role: 'status' }, 'Loading') };
    if (name === '@/lib/ats-api') return { atsApi: {}, activeRoleHeaders: () => ({}) };
    if (name === '@/components/clients/client-poc-fields') return load('components/clients/client-poc-fields.tsx');
    if (name === '@/components/ui/phone-input') return { PhoneInput: props => React.createElement('input', { id: props.id, type: 'tel', value: props.value, readOnly: true, 'data-country': props.defaultCountry }) };
    if (name === '@/lib/client-creation-contract') return load('lib/client-creation-contract.ts');
    if (name === '@/components/ui/button') return { Button: ({ children, ...props }) => React.createElement('button', props, children) };
    return require(name);
  };
  vm.runInNewContext(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, esModuleInterop: false } }).outputText,
    { exports, require: localRequire });
  return exports;
}

test('frontend contract exactly matches the backend source of truth', () => {
  const expected = '// Generated by scripts/sync-client-creation-contract.cjs. Do not edit directly.\n' + fs.readFileSync('../ats_backend/src/clients/client-creation.contract.ts', 'utf8');
  assert.equal(fs.readFileSync('lib/client-creation-contract.ts', 'utf8'), expected);
});
test('India form renders domestic fields and locked context without end-client or market switches', () => {
  const { ClientForm } = load('components/clients/client-form.tsx');
  const html = renderToStaticMarkup(React.createElement(ClientForm, { onCancel() {}, onSaved() {} }));
  assert.match(html, /India Domestic Market/);
  assert.match(html, /Kolkata/);
  assert.match(html, /India Staffing/);
  assert.match(html, /GSTIN/);
  assert.match(html, /PAN number/);
  assert.match(html, /Client category/);
  assert.match(html, /Billing address/);
  assert.match(html, /Submit for approval/);
  assert.doesNotMatch(html, /US IT Staffing|Federal EIN|End Client|name="market"/);
});
test('US context renders US tax fields while the same form remains locked', () => {
  const { ClientForm } = load('components/clients/client-form.tsx', { ...context, market: 'US', currency: 'USD', canDirectAdd: true });
  const html = renderToStaticMarkup(React.createElement(ClientForm, { onCancel() {}, onSaved() {} }));
  assert.match(html, /US IT Staffing/);
  assert.match(html, /Federal EIN/);
  assert.doesNotMatch(html, /GSTIN|PAN number/);
});
test('missing context and a mismatched job market block creation', () => {
  for (const [data, expectedMarket] of [[undefined, undefined], [context, 'US']]) {
    const { ClientForm } = load('components/clients/client-form.tsx', data, !data ? new Error('Unavailable') : undefined);
    const html = renderToStaticMarkup(React.createElement(ClientForm, { expectedMarket, onCancel() {}, onSaved() {} }));
    assert.match(html, /role="alert"/);
    assert.doesNotMatch(html, /type="submit"/);
  }
});

